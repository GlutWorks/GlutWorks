ix.anim.citizen_female_enhanced = EnhancedCitizen()

-- Overwatch models hold the rifle pose while unarmed instead of the stock unarmed sequences.
-- The fist, revolver and ar2 tables then come from these through the hold type fallback.
for _, holdType in ipairs({"normal", "pistol", "melee"}) do
	local tree = ix.anim.overwatch[holdType]

	tree[ACT_MP_STAND_IDLE] = {ACT_IDLE_SMG1, ACT_IDLE_ANGRY_SMG1}
	tree[ACT_MP_WALK] = {ACT_WALK_RIFLE, ACT_WALK_AIM_RIFLE}
	tree[ACT_MP_RUN] = {ACT_RUN_RIFLE, ACT_RUN_AIM_RIFLE}
end

-- Vortigaunts run without the aim activity, and walk without it while holding melee.
ix.anim.vortigaunt.normal[ACT_MP_RUN] = {ACT_RUN, ACT_RUN}
ix.anim.vortigaunt.melee[ACT_MP_RUN] = {ACT_RUN, ACT_RUN}
ix.anim.vortigaunt.melee[ACT_MP_WALK] = {ACT_WALK, ACT_WALK}
